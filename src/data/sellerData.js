export function getStoreBySlug(slug) {
  const formattedName = slug
    ? slug
        .split("-")
        .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
        .join("")
    : "NovaStore";

  return {
    ...storeData,
    seller: {
      ...storeData.seller,
      name: slug === "nova-store" ? "NovaStore" : formattedName || "NovaStore",
      slug: slug || "nova-store",
    },
  };
}
